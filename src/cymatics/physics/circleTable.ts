/** Normalised radial profile N·R(r) of a table row, evaluated exactly (CPU only). */
export function circleRadial(row: CircleModeRow, r: number): number {
  const [n, , lam, C, N] = row
  const x = lam * r
  return N * (besselJ(n, x) + C * besselI(n, x))
}

/** d/dr of `circleRadial`. */
export function circleRadialSlope(row: CircleModeRow, r: number): number {
  const [n, , lam, C, N] = row
  const x = lam * r
  return N * lam * (besselJp(n, x) + C * besselIp(n, x))
}
